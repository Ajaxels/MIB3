function keyShortcutsBtn_Callback(obj)
% KEYSHORTCUTSBTN_CALLBACK - Show all mouse, Shift+mouse, and keyboard controls
% available in the pair view / seam table as a single reference list.
%
% Syntax:
%   .. code-block:: matlab
%
%      obj.keyShortcutsBtn_Callback()
%

if obj.mibModel.preferences.System.DeveloperMode
    fprintf('controllers.StitchingInspector.keyShortcutsBtn_Callback: triggered\n');
end

htmlBody = ['<html><body style="font-family: sans-serif; font-size: 10pt">' ...
    '<p><b>Mouse &mdash; pair view</b></p><ul>' ...
    '<li><b>Left drag</b> &mdash; move tile <i>j</i> over tile <i>i</i> (Fix Z: the magenta ' ...
    'slice over the cyan one); release applies the fix</li>' ...
    '<li><b>Left click</b>, no movement &mdash; nothing, stray clicks never move a tile</li>' ...
    '<li><b>Left click</b> (Two-click match armed) &mdash; sets a landmark point on ' ...
    'whichever tile was clicked; the click difference between the two tiles becomes the offset</li>' ...
    '<li><b>Right drag</b> &mdash; pans the view, clamped to the rendered tile extent; ' ...
    'never edits alignment</li>' ...
    '<li><b>Wheel</b> &mdash; zooms the pair view at the cursor</li>' ...
    '</ul>' ...
    '<p><b>Shift + mouse &mdash; pair view</b></p><ul>' ...
    '<li><b>Shift + hover</b> &mdash; shows the correlation ROI box at the cursor (no click needed)</li>' ...
    '<li><b>Shift + left click</b> &mdash; click-to-correlate: cuts the ROI box and auto-snaps ' ...
    'to a confident sub-pixel match; a weak/ambiguous match reports why and never moves the tile</li>' ...
    '<li><b>Shift + wheel</b> &mdash; resizes the correlation ROI box (see ROI size)</li>' ...
    '</ul>' ...
    '<p><b>Mouse &mdash; elsewhere</b></p><ul>' ...
    '<li><b>Mini-map click</b> &mdash; jumps to review the seam nearest the click point</li>' ...
    '<li><b>Seam table row click</b> &mdash; selects that seam for review</li>' ...
    '</ul>' ...
    '<p><b>Keyboard shortcuts</b></p><ul>' ...
    '<li><b>Enter</b> &mdash; confirm the current seam and jump to the next worst unreviewed</li>' ...
    '<li><b>X</b> &mdash; exclude / re-include the current seam from the solve</li>' ...
    '<li><b>N</b> / <b>P</b> &mdash; next / previous seam in the ranking</li>' ...
    '<li><b>Q</b> / <b>W</b> or <b>Down</b> / <b>Up</b> &mdash; browse Z slices (Shift = &plusmn;5); ' ...
    'always view-only, in both Fix XY and Fix Z</li>' ...
    '<li><b>Z</b> &mdash; undo the fix on the current seam, restoring the original automatic edge ' ...
    '(Fix Z: removes the boundary correction on screen)</li>' ...
    '<li><b>F</b> &mdash; fit the pair view, resetting the mouse-wheel zoom</li>' ...
    '<li><b>Space</b> &mdash; flicker A/B (Flicker overlay mode)</li>' ...
    '</ul>' ...
    '<p><i>Positional fixes are mouse-only &mdash; the keyboard never moves a tile.</i></p>' ...
    '</body></html>'];

dlgOptions.MsgBoxOnly = true;
dlgOptions.Icon = 'puffin_info';
dlgOptions.WindowWidth = 560;
dlgOptions.WindowHeight = 660;
utils.dlgs.inputUniversalDlg(obj.view.gui, 'Stitching Inspector controls', {''}, {htmlBody}, ...
    'Key shortcuts', dlgOptions);

end
