function [hSplashScreen, hSplashAxes, hLabel] = showSplashScreen(obj, titleText, initText)
% function hSplashScreen = showSplashScreen(obj, titleText, initText)
% Show MIB splash screen while loading
%
% Parameters:
% titleText: char with the window title
% initText: char with the initial status text

arguments (Input)
    obj controllers.MibController
    titleText char = 'Splash screen'
    initText char = 'Please wait...'
end

arguments (Output)
    hSplashScreen 
    hSplashAxes
    hLabel
end

hSplashScreen = figure(...
    'Resize', 'off', ...
    'NumberTitle', 'off', ...
    'MenuBar', 'none', ...
    'Name', titleText, ...
    'Toolbar','none', ...
    'Units','pixels', ...
    'Visible','off');

hSplashAxes = axes(hSplashScreen, 'Units', 'normalized');

imshow(imread(fullfile(obj.mibPath, 'assets', 'images','mib_splashscreen.jpg')), ...
    'Parent', hSplashAxes, 'border', 'tight');
set(hSplashAxes,'Position', [0 0 1 1]);
set(gca, 'DataAspectRatioMode', 'auto');
movegui(hSplashScreen, 'center');

set(hSplashScreen,'Visible','on')

hLabel = text(hSplashAxes, 100, 350, ...
    initText, ...
    'Color', 'y', ...
    'VerticalAlignment', 'bottom', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'FixedWidth', ...
    'Fontweight', 'bold', ...
    'FontSize', 11, ...
    'Interpreter', 'none');

drawnow nocallbacks;
end