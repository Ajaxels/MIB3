function addDirContentsPanel(obj)
% function addDirContentsPanel(obj)
% add the Datasets panel, add context menus and callbacks for widgets

arguments (Input)
    obj views.MibView
end

%% ---------------------- DIRECTORY CONTENTS PANEL ----------------------
panelOptions.Title = "Directory contents";
panelOptions.Region = "left";
obj.handles.panels.dirContentsPanel = matlab.ui.internal.FigurePanel(panelOptions);
obj.handles.panels.dirContentsPanel.PreferredHeight = 220;
obj.handles.panels.dirContentsPanel.Figure.AutoResizeChildren = 'off';
obj.handles.panels.dirContents = views.components.DirectoryContents('Parent', obj.handles.panels.dirContentsPanel.Figure, ...
    'Units', 'normalized', 'Position', [0 0 1 1]); % needs to have normalized units, by default those are pixels
% add handle tags to tooltips
if obj.mibModel.developerMode; utils.overrideDescriptions(obj.handles.panels.dirContents.handles, true, 'obj.handles.panels.dirContents.handles'); end

% ---------------------- ADD CONTEXT MENUs ----------------------
% ---------------------- Add context menu for fileList ----------------------
obj.handles.panels.dirContents.handles.fileListContext = uicontextmenu(obj.handles.panels.dirContentsPanel.Figure);
obj.handles.panels.dirContents.handles.fileListContextCombine = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Combine selected datasets', 'Tag', 'fileListContextCombine', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextLoadPart = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Load part of dataset (AM, TIF, BioFormats)...', 'Tag', 'fileListContextLoadPart', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextLoadNth = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Load each N-th file...', 'Tag', 'fileListContextLoadNth', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextInsert = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Insert into open dataset...', 'Tag', 'fileListContextInsert', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
% ----
obj.handles.panels.dirContents.handles.fileListContextColorCombine = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Combine files as color channels...', 'Tag', 'fileListContextColorCombine', 'Separator', 'on', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextColorAdd = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Add as a new color channel...', 'Tag', 'fileListContextColorAdd', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextColorAddNth = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Add each N-th file as a new color channel...', 'Tag', 'fileListContextColorAddNth', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
% ----
obj.handles.panels.dirContents.handles.fileListContextRename = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Rename selected file...', 'Tag', 'fileListContextRename', 'Separator', 'on', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileListContextDelete = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'Delete selected files...', 'Tag', 'fileListContextDelete', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
% ----
obj.handles.panels.dirContents.handles.fileListContextProps = uimenu(obj.handles.panels.dirContents.handles.fileListContext, ...
    'Text', 'File properties', 'Tag', 'fileListContextProps', 'Separator', 'on', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileList_ContextMenu(src, event));
% Add the context menu to fileList
obj.handles.panels.dirContents.handles.fileList.ContextMenu = obj.handles.panels.dirContents.handles.fileListContext;

% ---------------------- Add context menu for fileFilters ----------------------
obj.handles.panels.dirContents.handles.fileFiltersContext = uicontextmenu(obj.handles.panels.dirContentsPanel.Figure);
obj.handles.panels.dirContents.handles.fileFiltersContextRegister = uimenu(obj.handles.panels.dirContents.handles.fileFiltersContext, ...
    'Text', 'Register extension', 'Tag', 'fileFiltersContextRegister', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileFilters_ContextMenu(src, event));
obj.handles.panels.dirContents.handles.fileFiltersContextUnregister = uimenu(obj.handles.panels.dirContents.handles.fileFiltersContext, ...
    'Text', 'Register extension', 'Tag', 'fileFiltersContextUnregister', ...
    'MenuSelectedFcn', @(src, event)obj.controller.dirContentsFileFilters_ContextMenu(src, event));
% Add the context menu to fileFilters
obj.handles.panels.dirContents.handles.fileFilters.ContextMenu = obj.handles.panels.dirContents.handles.fileFiltersContext;

% ----------------------ADD CALLBACKS TO WIDGETS ----------------------
obj.handles.panels.dirContents.handles.fileList.DoubleClickedFcn = @(src, event)obj.controller.dirContentsFileList_Callback(src, event);
obj.handles.panels.dirContents.handles.fileFilters.ValueChangedFcn = @(src, event)obj.controller.dirContentsFileFilters_Callback(src, event);
obj.handles.panels.dirContents.handles.bioFormats.ValueChangedFcn = @(src, event)obj.controller.dirContentsBioFormats_Callback(src, event);
obj.handles.panels.dirContents.handles.updateFileList.ButtonPushedFcn = @(src, event)obj.controller.dirContentsUpdateFileList_Callback(src, event);
obj.handles.panels.dirContents.handles.help.ButtonPushedFcn = @(src, event)obj.controller.helpButtons_Callback(src, event);

% add the panel to the gui
obj.gui.add(obj.handles.panels.dirContentsPanel);


end